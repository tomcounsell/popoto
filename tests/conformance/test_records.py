"""Record-family conformance: families B, C and ``purge_orphan`` (#631 WS3a).

Every test here runs on every configured backend with the *same* assertions:
``RedisBackend`` is the oracle (its bodies are today's code, moved verbatim in
WS0), so whatever it returns is what ``PostgresBackend`` must return. The
increment table below was generated by running the Redis path and recording
the return value and the stored bytes; the Redis leg re-validates the table
on every run and the Postgres leg is held to it.

Two helpers reach past the protocol: ``seed_index`` and ``index_has`` put a
member into a sorted or set index (Redis: ``ZADD``/``SADD`` on the plugin-bound
client; Postgres: a row in ``popoto_sorted``/``popoto_set`` through the
backend's own connection). ``purge_orphan`` needs an orphaned membership to
prune and the protocol methods that would create one (``sorted_add``,
``index_add``) are WS3b's, still stubs on Postgres.

Never touches database 0 or schema ``public``: the Redis leg goes through the
plugin-bound client and the Postgres leg through the harness's own schema.
"""

from __future__ import annotations

import struct
import threading
import time
from decimal import Decimal
from typing import Any

import msgpack
import pytest

from popoto.backends import postgres as postgres_module
from popoto.backends.postgres import PostgresBackend
from popoto.backends.redis import RedisBackend

pytestmark = pytest.mark.conformance

PREFIX = "popoto_test:631:records"
CLASS_SET = f"$Class:{PREFIX}:Record"


def key(suffix: Any) -> str:
    return f"{PREFIX}:Record:{suffix}"


def seed_index(backend: Any, idx: str, kind: str, member: str) -> None:
    """Put ``member`` into index ``idx`` outside the protocol (see module doc)."""
    if isinstance(backend, RedisBackend):
        if kind == "sorted":
            backend.client.zadd(idx, {member: 1.0})
        else:
            backend.client.sadd(idx, member)
        return
    assert isinstance(backend, PostgresBackend)
    conn = backend._connection()
    if kind == "sorted":
        conn.execute(
            "INSERT INTO popoto_sorted (idx, member, score) VALUES (%s, %s, 1.0) "
            "ON CONFLICT DO NOTHING",
            (idx, member),
        )
    else:
        conn.execute(
            "INSERT INTO popoto_set (idx, member) VALUES (%s, %s) "
            "ON CONFLICT DO NOTHING",
            (idx, member),
        )


def index_has(backend: Any, idx: str, kind: str, member: str) -> bool:
    if isinstance(backend, RedisBackend):
        if kind == "sorted":
            return backend.client.zscore(idx, member) is not None
        return bool(backend.client.sismember(idx, member))
    assert isinstance(backend, PostgresBackend)
    table = "popoto_sorted" if kind == "sorted" else "popoto_set"
    row = (
        backend._connection()
        .execute(f"SELECT 1 FROM {table} WHERE idx = %s AND member = %s", (idx, member))
        .fetchone()
    )
    return row is not None


